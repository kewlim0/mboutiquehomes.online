function listingIdFromUrl() {
    const m = LISTING_PATH.exec(location.pathname);
    if (m) return m[2];
    const q = new URLSearchParams(location.search).get('listing');
    return q && /^[A-Za-z0-9]+$/.test(q) ? q : null;
}

