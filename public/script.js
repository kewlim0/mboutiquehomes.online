// Apply the current language to all static (data-i18n) and dynamic content
function applyLanguage() {
    document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';
    applyTitle();

    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = i18n[el.dataset.i18n][currentLang];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = i18n[el.dataset.i18nPlaceholder][currentLang];
    });

    // Highlight the active language in the toggle button
    document.getElementById('langZh').className = 'lang-opt' + (currentLang === 'zh' ? ' active' : '');
    document.getElementById('langEn').className = 'lang-opt' + (currentLang === 'en' ? ' active' : '');

    renderProperties();
    renderTeam();
    if (currentDetail && isModalOpen(document.getElementById('detailModal'))) {
        openDetailModal(currentDetail, true);
    }
}

// Toggle Chinese / English
function toggleLanguage() {
    currentLang = currentLang === 'zh' ? 'en' : 'zh';
    try { localStorage.setItem(LANG_KEY, currentLang); } catch (e) { /* ignore */ }
    applyLanguage();
    // from now on the address names the language: /EN or /CH (and /EN/listings, /EN/listing/<code>)
    langInUrl = true;
    if (currentDetail && isListingPath()) history.replaceState(history.state, '', listingUrl(currentDetail));
    syncLangUrl();
}

