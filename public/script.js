// Open the detail modal. While its image loads, the modal shows a skeleton (skipped when `instant` is true,
// e.g. when only the language changed).
function openDetailModal(item, instant = false) {
    const L = currentLang;
    currentDetail = item;
    const modal = document.getElementById('detailModal');
    const gallery = document.getElementById('modalGallery');
    const photos = item.photos && item.photos.length ? item.photos : [item.img];
    const token = ++detailLoadToken;

    // the "real photo" caption only makes sense on a single big picture
    document.getElementById('modalImgCaption').classList.toggle('hidden', photos.length > 1);

    if (instant) {
        gallery.innerHTML = Store.galleryHtml(photos);
    } else {
        modal.classList.add('is-loading');
        gallery.innerHTML = '';

        // wait for the cover picture (the others load by themselves, each with its own placeholder)
        const imageReady = Promise.race([
            new Promise(resolve => {
                const img = new Image();
                img.onload = img.onerror = resolve;
                img.src = Store.resolve(photos[0]);
            }),
            new Promise(resolve => setTimeout(resolve, 4000))
        ]);
        Promise.all([imageReady, new Promise(resolve => setTimeout(resolve, 600))]).then(() => {
            if (token !== detailLoadToken) return; // modal was closed or reopened for another listing
            gallery.innerHTML = Store.galleryHtml(photos);
            modal.classList.remove('is-loading');
        });
    }

    document.getElementById('modalTitle').innerText = item.title[L];
    document.getElementById('modalPrice').innerText = formatPrice(item.priceRM, item.isRentPrice);
    document.getElementById('modalLocation').innerHTML = `<i class="fa-solid fa-location-dot text-gold-600 mr-1"></i> ${esc(item.address)}`;
    document.getElementById('shareBtnLabel').textContent = ui('copyLink');
    document.getElementById('modalArea').innerText = formatArea(item.areaSqft);
    document.getElementById('modalBeds').innerHTML = bedsHtml(item, L);
    document.getElementById('modalFurnish').innerText = item.status[L];
    document.getElementById('modalDesc').innerText = item.desc[L];

    renderHighlights(item, L);

    // a notice when the home is only free from a later date
    const avail = availableText(item);
    document.getElementById('modalAvailable').classList.toggle('hidden', !avail);
    document.getElementById('modalAvailableText').textContent = avail;

    // sold / rented: say so clearly and stop the "book a viewing" button
    const closedBadge = document.getElementById('modalClosedBadge');
    closedBadge.textContent = closedLabel(item);
    closedBadge.classList.toggle('hidden', !item.closed);
    const book = document.getElementById('modalBookBtn');
    const bookText = book.querySelector('[data-i18n="waBook"]');
    book.classList.toggle('is-closed', !!item.closed);
    if (item.closed) {
        book.removeAttribute('href');
        book.setAttribute('aria-disabled', 'true');
        bookText.textContent = closedLabel(item);
    } else {
        book.href = 'https://api.whatsapp.com/send?phone=60149314514';
        book.removeAttribute('aria-disabled');
        bookText.textContent = i18n.waBook[L];
    }

    const badge = document.getElementById('modalTypeBadge');
    badge.innerText = ui(item.type);
    badge.className = `absolute top-3 left-3 px-2.5 py-1 rounded-full text-[10px] font-bold uppercase tracking-wider text-white shadow-md ${item.type === 'rent' ? 'bg-gold-500' : 'bg-charcoal-900'}`;

    showModal(document.getElementById('detailModal'));
    applyTitle(); // the tab title becomes the listing's name
}

function closeDetailModal(fromBrowserBack = false) {
    detailLoadToken++;
    hideModal(document.getElementById('detailModal'));
    applyTitle();
    // the address was /listing/12 while the sheet was open: put it back
    if (!fromBrowserBack && isListingPath()) {
        if (listingEntryPushed) {
            listingEntryPushed = false;
            history.back();                       // we added that history entry ourselves: remove it
        } else {
            history.replaceState(null, '', homePath());  // arrived through a shared link: there is nothing to go back to
        }
    }
}

// ---------- Full-screen photo viewer ----------
const lightboxEl = document.getElementById('lightbox');
let lightboxIndex = 0;
let lightboxCount = 0;

function updateLightbox() {
    const track = document.getElementById('lbTrack');
    lightboxIndex = Math.max(0, Math.min(lightboxCount - 1, Math.round(track.scrollLeft / Math.max(1, track.clientWidth))));
    document.getElementById('lbCount').textContent = `${lightboxIndex + 1} / ${lightboxCount}`;
    document.getElementById('lbPrev').disabled = lightboxIndex === 0;
    document.getElementById('lbNext').disabled = lightboxIndex >= lightboxCount - 1;
}

function openLightbox(photos, index = 0) {
    if (!lightboxEl || !photos || !photos.length) return;
    const track = document.getElementById('lbTrack');
    lightboxCount = photos.length;
    track.innerHTML = photos.map((p, i) => `
        <div class="lb-slide"><img src="${esc(Store.resolve(p))}" alt="" ${i === index ? '' : 'loading="lazy"'}
            onerror="this.onerror=null;this.src='https://placehold.co/800x600/1e293b/ffffff?text=Luxe+Property'"></div>`).join('');
    lightboxEl.classList.remove('hidden', 'is-closing');
    track.style.scrollBehavior = 'auto';
    track.scrollLeft = index * track.clientWidth;
    track.style.scrollBehavior = '';
    updateLightbox();
}

function closeLightbox() {
    if (!lightboxEl || lightboxEl.classList.contains('hidden') || lightboxEl.classList.contains('is-closing')) return;
    lightboxEl.classList.add('is-closing');
    setTimeout(() => { lightboxEl.classList.add('hidden'); lightboxEl.classList.remove('is-closing'); }, 200);
}

if (lightboxEl) {
    const track = document.getElementById('lbTrack');
    let scrollTimer;
    track.addEventListener('scroll', () => { clearTimeout(scrollTimer); scrollTimer = setTimeout(updateLightbox, 60); });
    document.getElementById('lbClose').addEventListener('click', closeLightbox);
    document.getElementById('lbPrev').addEventListener('click', () => track.scrollBy({ left: -track.clientWidth, behavior: 'smooth' }));
    document.getElementById('lbNext').addEventListener('click', () => track.scrollBy({ left: track.clientWidth, behavior: 'smooth' }));
    // tapping the dark area around a picture closes the viewer
    track.addEventListener('click', (e) => { if (e.target.tagName !== 'IMG') closeLightbox(); });
    // capture phase: while the viewer is open, Escape / arrows belong to it and not to the sheet underneath
    document.addEventListener('keydown', (e) => {
        if (lightboxEl.classList.contains('hidden')) return;
        if (e.key === 'Escape') { e.stopImmediatePropagation(); closeLightbox(); }
        else if (e.key === 'ArrowLeft') track.scrollBy({ left: -track.clientWidth, behavior: 'smooth' });
        else if (e.key === 'ArrowRight') track.scrollBy({ left: track.clientWidth, behavior: 'smooth' });
    }, true);
}

