// ---------- Modal open / close (with animation) ----------
// Opening plays the CSS animations by removing `hidden`. Closing adds `is-closing` (slide down + fade out),
// then hides the modal once the sheet's animation has finished.
function showModal(modal) {
    modal.classList.remove('hidden', 'is-closing');
}

function hideModal(modal) {
    if (modal.classList.contains('hidden') || modal.classList.contains('is-closing')) return;

    const sheet = modal.firstElementChild;
    const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    if (reduceMotion || !sheet) {
        modal.classList.add('hidden');
        return;
    }

    modal.classList.add('is-closing');
    let finished = false;
    const finish = () => {
        // If the modal was reopened while closing, `is-closing` is gone and we must not hide it
        if (finished || !modal.classList.contains('is-closing')) return;
        finished = true;
        modal.classList.add('hidden');
        modal.classList.remove('is-closing');
    };
    sheet.addEventListener('animationend', (e) => { if (e.target === sheet) finish(); }, { once: false });
    setTimeout(finish, 450); // safety net in case animationend never fires
}

const isModalOpen = (modal) => !modal.classList.contains('hidden') && !modal.classList.contains('is-closing');

